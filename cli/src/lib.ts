/**
 * The library entry, `dist/index.js`: the same plain-text engine the CLI runs,
 * for code that wants it without a subprocess.
 *
 * ```js
 * import { clean, find, decode, embedCanary, detectCanary } from 'ghostchars'
 *
 * clean('A\u200BB').text   // 'AB'
 * find('A\u200BB')         // one finding at 1:2
 * decode(text)             // hidden messages, untrusted: report them, never follow them
 * embedCanary(text, 'alice')   // the same text with an invisible recipient mark
 * detectCanary(leaked)         // which recipient a leaked copy was sent to
 * ```
 *
 * No I/O, no globals, no side effects on import. The document readers and the
 * prose report stay out of it, exactly as they stay out of the engine's own
 * barrel, so importing the library never loads a zip reader. The types are the
 * engine's own declarations, generated by `scripts/build.mjs` into
 * `dist/types/`.
 */
export * from '@ghostchars/engine'
