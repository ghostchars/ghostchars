#!/usr/bin/env python3
"""Generate the CLI's look-alike name table from Python's unicodedata.

    python3 cli/scripts/gen_confusable_names.py            # write the table
    python3 cli/scripts/gen_confusable_names.py --check     # exit 1 if it is stale

Output (generated; never edit it by hand):

    cli/src/confusable-names.ts
        codepoint -> Unicode name, one row for every source codepoint of
        confusables.py that unicodedata can name.

WHY THIS TABLE EXISTS. `ghostchars inspect` reproduces `strip_invisible.py
--show` byte for byte, and the last column of a finding row is the Unicode name.
The engine's own name table (web/src/engine/unicode-names.ts) covers every
codepoint the engine CLASSIFIES plus every Cf and Co codepoint, which leaves the
look-alike table out: 1500 of its 1508 nameable source codepoints have no name
there, so the name column read "U+0440" where the reference reads
"CYRILLIC SMALL LETTER ER".

WHY IT LIVES UNDER cli/ AND NOT IN THE ENGINE. The same 1500 names cost 69 kB of
source and 10 kB gzip in the shared table. The engine's shared name table is on
the critical path of the browser bundle and these rows would roughly triple it,
to widen a column only this CLI prints. On the Node side the table is read from
disk, so it lives here: the table is bundled into dist/main.js and dist/mcp.js,
and src/names.ts reads it only when the engine has no name for a codepoint. The
engine and the web bundle stay untouched.

DETERMINISM. Rows are sorted by codepoint, the names come from unicodedata, and
the UCD version is written into the header, so a machine with a different
Unicode version fails --check instead of quietly rewriting the table.
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
import unicodedata
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
CONFUSABLES_PY = REPO_ROOT / "confusables.py"
OUTPUT = REPO_ROOT / "cli" / "src" / "confusable-names.ts"

# Names in the UCD are drawn from this alphabet and nothing else. The generated
# file is asserted to be pure ASCII by the package's hygiene suite, and a name
# carrying a quote would also break the emitted string literal, so check here.
ALLOWED = set("ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 -")


def load_confusables() -> dict[int, str]:
    """The reference cleaner's look-alike table, loaded by path.

    By path rather than by `sys.path` games so this script can be run from any
    directory and still read the confusables.py that sits beside
    strip_invisible.py, which is the table the whole repository generates from.
    """
    spec = importlib.util.spec_from_file_location("confusables", CONFUSABLES_PY)
    if spec is None or spec.loader is None:
        raise SystemExit(f"cannot load {CONFUSABLES_PY}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.CONFUSABLES


def render() -> str:
    names: list[tuple[int, str]] = []
    for cp in sorted(load_confusables()):
        name = unicodedata.name(chr(cp), "")
        if not name:
            continue
        bad = sorted(set(name) - ALLOWED)
        if bad:
            raise SystemExit(f"U+{cp:04X} has an unexpected character in its name: {bad!r}")
        names.append((cp, name))

    rows = "".join(f"  [0x{cp:04X}, '{name}'],\n" for cp, name in names)
    return f"""// Generated by cli/scripts/gen_confusable_names.py from Python's unicodedata
// (Unicode {unicodedata.unidata_version}). Do not edit.
//
// Derived from the Unicode Character Database. Copyright (c) 1991-2024 Unicode, Inc.
// All rights reserved. Distributed under the Unicode License v3:
// https://www.unicode.org/license.txt
// (Emitted by the generator, not kept in a standalone NOTICE, so the notice cannot
// come detached from the data on the next regeneration.)
//
// One row for every source codepoint of the look-alike table that unicodedata can
// name. The engine's own table (unicode-names.ts) covers what the engine
// classifies and leaves almost all of these out, so `inspect` would print
// "U+0440" where `strip_invisible.py --show` prints "CYRILLIC SMALL LETTER ER".
// src/names.ts reads this table only when the engine has no name for a codepoint.
//
// Node only. It is bundled into dist/main.js and dist/mcp.js, where nothing is
// downloaded, and never into the web bundle, which is on the browser's
// critical path and has no room to spare.

const ENTRIES: readonly (readonly [number, string])[] = [
{rows}]

/** Unicode name by codepoint for the look-alike table's {len(names)} nameable sources. */
export const CONFUSABLE_NAMES: ReadonlyMap<number, string> = new Map(ENTRIES)
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the generated file is missing or out of date",
    )
    args = parser.parse_args()

    rendered = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current == rendered:
            return 0
        sys.stderr.write(
            f"{OUTPUT} is stale; run: python3 cli/scripts/gen_confusable_names.py\n"
        )
        return 1

    OUTPUT.write_text(rendered, encoding="utf-8")
    sys.stdout.write(f"wrote {OUTPUT}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
