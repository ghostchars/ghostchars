#!/usr/bin/env python3
"""Generate confusables.py / web/src/engine/confusables.ts from Unicode data.

    curl -sLO https://www.unicode.org/Public/security/latest/confusables.txt
    python3 tools/gen_confusables.py confusables.txt > confusables.py
    python3 tools/gen_confusables.py --ts confusables.py > web/src/engine/confusables.ts
    python3 tools/gen_confusables.py --swift confusables.py > Confusables.generated.swift

The source may be Unicode's confusables.txt or the already-generated
confusables.py; the second form regenerates the TypeScript (or Swift) table
from the data already in the repo, without refetching. All three emitters read
the same mapping, so the Python, TypeScript and Swift tables cannot drift.

`--swift` emits the table as Swift source for a native port.

confusables.txt maps characters to a comparison *skeleton*, which is lossy for
cleaning: 1, I and | all skeletonize to l, and 0 to O. This script keeps only
non-ASCII sources whose skeleton is 1-3 ASCII alphanumerics, and resolves the
ambiguous targets from the source's general category (Lu -> I/O, Nd -> 1/0,
Ll -> l/o, other -> |). Case of single-letter targets follows the source.
"""
import argparse
import ast
import json
import sys
import unicodedata

# Unicode's licence requires its copyright and permission notice to accompany
# distributions of its data. `confusables.ts` IS a distribution of that data:
# it ships to every visitor's browser, so the notice is emitted into the file
# itself, where a regeneration cannot lose it.
UNICODE_NOTICE = (
    "// Derived from data published by Unicode, Inc. (confusables.txt).",
    "// Copyright (c) 1991-2024 Unicode, Inc. All rights reserved.",
    "// Distributed under the Unicode License v3: https://www.unicode.org/license.txt",
)

def resolve(src_cp: int, tgt: str) -> str:
    ch = chr(src_cp)
    cat = unicodedata.category(ch)
    # Roman numerals are Nl but cased; caseless letter-numbers read as caps.
    upper = ch.isupper() or (cat == "Nl" and not ch.islower())
    if len(tgt) == 1:
        if tgt == "l":
            if upper:
                return "I"
            return {"Nd": "1", "No": "1", "Ll": "l", "Lo": "l", "Lm": "l"}.get(cat, "|")
        if tgt == "O":
            if upper:
                return "O"
            return {"Nd": "0", "No": "0"}.get(cat, "o")
        if tgt.isalpha():
            if upper:
                return tgt.upper()
            if cat == "Ll":
                return tgt.lower()
        return tgt
    return tgt.replace("l", "I") if upper else tgt

def parse_unicode_data(path: str) -> dict[int, str]:
    out = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            src, tgt, *_ = [x.strip() for x in line.split(";")]
            if " " in src:
                continue  # multi-codepoint sources are sequences, not lookalikes
            s = int(src, 16)
            if s < 0x80:
                continue
            t = "".join(chr(int(x, 16)) for x in tgt.split())
            if not (1 <= len(t) <= 3 and t.isascii() and t.isalnum()):
                continue
            out[s] = resolve(s, t)
    return out

def parse_generated_module(path: str) -> dict[int, str]:
    """Read CONFUSABLES back out of the generated confusables.py, without importing it."""
    with open(path, encoding="utf-8") as f:
        tree = ast.parse(f.read(), filename=path)
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "CONFUSABLES" for t in node.targets):
            table = ast.literal_eval(node.value)
            return {int(k): str(v) for k, v in table.items()}
    raise SystemExit(f"{path}: no CONFUSABLES assignment found")

def load(path: str) -> dict[int, str]:
    return parse_generated_module(path) if path.endswith(".py") else parse_unicode_data(path)

def emit_python(table: dict[int, str], out) -> None:
    print('"""Glyph-confusable lookalikes -> ASCII. Generated by tools/gen_confusables.py."""',
          file=out)
    print("CONFUSABLES = {", file=out)
    for cp in sorted(table):
        name = unicodedata.name(chr(cp), "<unnamed>")
        print(f"    0x{cp:04X}: {table[cp]!r},  # {name}", file=out)
    print("}", file=out)

def emit_ts(table: dict[int, str], out) -> None:
    print("// Glyph-confusable lookalikes -> ASCII. Generated by "
          "`tools/gen_confusables.py --ts`. Do not edit.", file=out)
    print("//", file=out)
    for line in UNICODE_NOTICE:
        print(line, file=out)
    print("//", file=out)
    print("// Unicode confusables.txt reduced to non-ASCII sources whose skeleton is 1-3 ASCII",
          file=out)
    print("// alphanumerics; see the docstring of tools/gen_confusables.py for how ambiguous",
          file=out)
    print("// targets are resolved. The engine consults this table only for a codepoint inside a",
          file=out)
    print("// MIXED-SCRIPT word (classify.ts inMixedScriptWord), so pure Cyrillic/Greek prose is",
          file=out)
    print("// never touched; the option stays opt-in because it rewrites visible letters.", file=out)
    print("", file=out)
    print("const ENTRIES: readonly (readonly [number, string])[] = [", file=out)
    for cp in sorted(table):
        print(f"  [0x{cp:04X}, {json.dumps(table[cp])}],", file=out)
    print("];", file=out)
    print("", file=out)
    print("/** Confusable codepoint -> the ASCII letter or digit it imitates. */", file=out)
    print("export const CONFUSABLES: ReadonlyMap<number, string> = new Map(ENTRIES);", file=out)

def swift_string_literal(value: str) -> str:
    """Swift's string-literal escaping is a strict subset of JSON's for this
    data (targets are ASCII alnum, 1-3 chars, per the module docstring), so
    reusing `json.dumps` -- as `emit_ts` already does -- is exact here too."""
    return json.dumps(value)

def emit_swift(table: dict[int, str], out) -> None:
    print("// Glyph-confusable lookalikes -> ASCII. Generated by "
          "`tools/gen_confusables.py --swift`. Do not edit.", file=out)
    print("//", file=out)
    for line in UNICODE_NOTICE:
        print(line, file=out)
    print("//", file=out)
    print("// Mirrors web/src/engine/confusables.ts (same source data, same resolution", file=out)
    print("// rules -- see the docstring of tools/gen_confusables.py); the engine consults", file=out)
    print("// this table only for a codepoint inside a MIXED-SCRIPT word.", file=out)
    print("", file=out)
    print("/// Confusable codepoint -> the ASCII letter or digit it imitates.", file=out)
    print("public enum Confusables {", file=out)
    print("    public static let table: [UInt32: String] = [", file=out)
    for cp in sorted(table):
        print(f"        0x{cp:04X}: {swift_string_literal(table[cp])},", file=out)
    print("    ]", file=out)
    print("}", file=out)

def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("source", help="confusables.txt from Unicode, or the generated confusables.py")
    fmt = p.add_mutually_exclusive_group()
    fmt.add_argument("--ts", action="store_true",
                   help="emit the TypeScript table instead of the Python one")
    fmt.add_argument("--swift", action="store_true",
                   help="emit the table as Swift source for a native port, instead of the Python one")
    args = p.parse_args()

    table = load(args.source)
    emitter = emit_swift if args.swift else emit_ts if args.ts else emit_python
    emitter(table, sys.stdout)
    return 0

if __name__ == "__main__":
    sys.exit(main())
